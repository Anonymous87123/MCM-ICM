clear;clc
v=0.2;
b=1/6000;
te=7200;
R=0.65;
r=0.2;
dc=2*10^(-2);
e=2*10^(-4);
syms beita;
a1=dc*beita^(-2);
a2=e*beita^2;
h=3*v/(pi*(R^2+r^2+R*r));
tf=3*v/(b*pi*(R^2+r^2+R*r));
hfinal=h-2*a2*(te-tf);
s21=2*v/(pi*sqrt((R-r)^2*(R^2+r^2+R*r)^2+v^2));
l1=a1*s21;
L1=2*l1+2*a2*te;
L2=2*a2*te;
Rfinal=(2*R-L1-L2)/2;
rfinal=r-(l1+a2*(te-tf));
a=pi*hfinal*(Rfinal^2+rfinal^2+Rfinal*rfinal)/(3*v);
f=diff(a,beita);
solve(f==0,beita)
